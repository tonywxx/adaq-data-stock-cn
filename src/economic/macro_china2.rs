//! `datacenter-web.eastmoney.com/api/data/v1/get` functions from
//! `akshare/economic/macro_china.py`).
//!
//! All 25 functions below are PURE HTTP: a single `GET` to the Eastmoney
//! datacenter JSON API (no JS / token / signature / `execjs` / cookie). They split
//! into two shapes:
//!
//! * **Group A — `RPT_INDUSTRY_INDEX`** (16 fns): one reportName, filtered by
//!   `INDICATOR_ID`, always returning the same 8-column layout
//!   (`REPORT_DATE`, `INDICATOR_VALUE`, `CHANGE_RATE`, `CHANGERATE_3M/6M/1Y/2Y/3Y`).
//!   A single [`IndustryIndexRow`] struct and [`parse_industry_index`] parser serve
