use serde_json::Value;

use crate::core::client::Client;
use crate::core::error::{Error, Result};

const SOURCE_EASTMONEY: &str = "eastmoney";
const BASE: &str = "https://datacenter-web.eastmoney.com/api/data/v1/get";

/// Extract `result.data` (the row array) from a datacenter-web response.
fn emg_data_array(resp: &Value) -> Result<&Vec<Value>> {
    resp.get("result")
        .and_then(|r| r.get("data"))
        .and_then(|d| d.as_array())
        .ok_or_else(|| Error::UpstreamChanged {
            origin: SOURCE_EASTMONEY,
            message: "missing result.data".into(),
        })
}

fn fstr(item: &Value, k: &str) -> Option<String> {
    item.get(k).and_then(|v| v.as_str()).map(|s| s.to_string())
}

fn fnum(item: &Value, k: &str) -> Option<f64> {
    item.get(k).and_then(|v| match v {
        Value::Number(n) => n.as_f64(),
        Value::String(s) => s.trim().parse::<f64>().ok(),
        _ => None,
    })
}

/// Shared fetch for every datacenter-web indicator in this module.
///
/// Builds the standard Eastmoney `RPT_*` request (optionally filtered by
/// `INDICATOR_ID`), returns the raw `result.data` row array for the caller's
/// `parse_*` function to turn into typed rows.
#[allow(clippy::too_many_arguments)]
async fn emdc_fetch(
    client: &Client,
    fn_name: &'static str,
    report_name: &str,
    columns: &str,
    page_size: &str,
    sort_columns: &str,
    sort_types: &str,
    filter: Option<&str>,
) -> Result<Vec<Value>> {
    let mut params: Vec<(&str, &str)> = vec![
        ("reportName", report_name),
        ("columns", columns),
        ("pageNumber", "1"),
        ("pageSize", page_size),
        ("sortColumns", sort_columns),
        ("sortTypes", sort_types),
        ("source", "WEB"),
        ("client", "WEB"),
        ("p", "1"),
        ("pageNo", "1"),
        ("pageNum", "1"),
    ];
    if let Some(f) = filter {
        params.push(("filter", f));
    }
    let v = client
        .get_json(SOURCE_EASTMONEY, fn_name, BASE, &params)
        .await?;
    emg_data_array(&v).cloned()
}

